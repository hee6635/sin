fs = json.load(open(sys.argv[1], encoding='utf-8'))['features']
def cen(g):
  polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
  r = max((p[0] for p in polys), key=len)
  return sum(x for x, _ in r) / len(r), sum(y for _, y in r) / len(r)
out = []
for no, nm, sd, sg in ST:
  pts = [cen(f['geometry']) for f in fs if f['properties']['sidonm'].startswith(sd) and f['properties']['sggnm'].startswith(sg)]
  assert pts, (no, nm)
  lon = sum(p[0] for p in pts) / len(pts); lat = sum(p[1] for p in pts) / len(pts)
  out.append([no, nm, round(lat, 3), round(lon, 3)])
dst = os.path.join(os.path.dirname(__file__), '../../firebase/functions/lib/wxAsos.json')
open(dst, 'w', encoding='utf-8').write('[\n' + ',\n'.join(json.dumps(x, ensure_ascii=False) for x in out) + '\n]\n')
print(len(out), 'stations →', os.path.normpath(dst))
